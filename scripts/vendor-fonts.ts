import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { getInfo as interInfo } from "@remotion/google-fonts/Inter";
import { getInfo as bvpInfo } from "@remotion/google-fonts/BeVietnamPro";
import { getInfo as cascadiaInfo } from "@remotion/google-fonts/CascadiaMono";

/**
 * Vendor the render-safe fonts into the repo (offline render, Property 19 made
 * network-independent).
 *
 * WHY: `@remotion/google-fonts` fetches each woff2 from `fonts.gstatic.com`
 * inside headless Chromium on EVERY render, gated by a hard 18s `delayRender`
 * timeout baked into the package. A slow or blocked network therefore KILLS an
 * otherwise-fine render ("Timed out loading Google Font") — a cosmetic asset
 * taking down the whole pipeline. That violates the project's "no network in the
 * hot path, deterministic" rule.
 *
 * WHAT: download exactly the weights + subsets the renderer uses, base64-encode
 * each woff2, and emit `packages/blocks/src/vendor-fonts.generated.ts` as a
 * manifest of `{ family, weight, style, unicodeRange, dataUrl }`. A data: URL is
 * a plain string, so the generated module loads IDENTICALLY in Node (vitest, no
 * FontFace — inert) and in the browser render (real FontFace) — unlike a static
 * `import x.woff2`, which would crash a Node import. `fonts.ts` then registers
 * these locally with zero network. Re-run this script to refresh (e.g. a font
 * version bump); the output is committed so renders never need the network.
 *
 * Usage: npx tsx scripts/vendor-fonts.ts
 */

// The exact families / weights / subsets loaded by packages/blocks/src/fonts.ts.
// Keep in sync with that file's loadFont() calls.
const FONT_PLAN: { info: () => FontInfo; weights: string[] }[] = [
  { info: interInfo, weights: ["400", "700", "800", "900"] },
  { info: bvpInfo, weights: ["400", "600", "700", "800", "900"] },
  { info: cascadiaInfo, weights: ["400", "700"] },
];
const SUBSETS = ["vietnamese", "latin"] as const;
const STYLE = "normal";

type FontInfo = {
  fontFamily: string;
  fonts: Record<string, Record<string, Record<string, string>>>;
  unicodeRanges: Record<string, string>;
};

type VendoredFont = {
  family: string;
  weight: string;
  style: string;
  subset: string;
  unicodeRange: string;
  dataUrl: string;
};

function here(): string {
  return dirname(fileURLToPath(import.meta.url));
}

async function fetchWoff2AsDataUrl(url: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} fetching ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  return `data:font/woff2;base64,${buf.toString("base64")}`;
}

async function main(): Promise<void> {
  const vendored: VendoredFont[] = [];
  let totalBytes = 0;

  for (const { info, weights } of FONT_PLAN) {
    const meta = info();
    const family = meta.fontFamily;
    for (const weight of weights) {
      for (const subset of SUBSETS) {
        const url = meta.fonts[STYLE]?.[weight]?.[subset];
        const unicodeRange = meta.unicodeRanges[subset];
        if (!url || !unicodeRange) {
          throw new Error(`Missing ${family} ${STYLE} ${weight} ${subset} in google-fonts metadata`);
        }
        process.stdout.write(`[vendor-fonts] ${family} ${weight} ${subset} … `);
        const dataUrl = await fetchWoff2AsDataUrl(url);
        totalBytes += dataUrl.length;
        console.log(`${(dataUrl.length / 1024).toFixed(0)} KB`);
        vendored.push({ family, weight, style: STYLE, subset, unicodeRange, dataUrl });
      }
    }
  }

  const outPath = resolve(here(), "..", "packages", "blocks", "src", "vendor-fonts.generated.ts");
  await mkdir(dirname(outPath), { recursive: true });

  const header = `// AUTO-GENERATED by scripts/vendor-fonts.ts — DO NOT EDIT BY HAND.
// Vendored render-safe fonts as base64 woff2 data URLs, so renders load fonts
// LOCALLY with no network (no "Timed out loading Google Font" failures). A data:
// URL is a plain string, so this module is inert in Node and real in the browser.
// Re-run \`npx tsx scripts/vendor-fonts.ts\` to refresh.

export type VendoredFont = {
  family: string;
  weight: string;
  style: string;
  subset: string;
  unicodeRange: string;
  dataUrl: string;
};

export const VENDORED_FONTS: VendoredFont[] = [
`;

  const body = vendored
    .map((f) => {
      return (
        `  {\n` +
        `    family: ${JSON.stringify(f.family)},\n` +
        `    weight: ${JSON.stringify(f.weight)},\n` +
        `    style: ${JSON.stringify(f.style)},\n` +
        `    subset: ${JSON.stringify(f.subset)},\n` +
        `    unicodeRange: ${JSON.stringify(f.unicodeRange)},\n` +
        `    dataUrl: ${JSON.stringify(f.dataUrl)},\n` +
        `  },`
      );
    })
    .join("\n");

  await writeFile(outPath, `${header}${body}\n];\n`, "utf8");
  console.log(
    `[vendor-fonts] wrote ${vendored.length} fonts (${(totalBytes / 1024 / 1024).toFixed(2)} MB base64) → ${outPath}`,
  );
}

main().catch((err) => {
  console.error("[vendor-fonts] FAILED:", err);
  process.exit(1);
});
